"""
Model Registry management module for Phase 2 Productionization.

Provides:
1. Programmatic access and versioning for trained models.
2. MLflow Model Registry integration with stage transitions (Staging -> Production -> Archived).
3. Local auditable registry manifest (models/model_registry.json) with cryptographic hashes,
   performance metrics, input feature schemas, and deployment readiness checks.
"""

from datetime import datetime
import hashlib
import json
from pathlib import Path
from typing import Any, Dict, Optional, Tuple
import joblib
from loguru import logger
import mlflow
from mlflow.tracking import MlflowClient

from src.config import AppConfig, load_config
from src.data_loader import CENTURY_21_SKILLS


class ModelRegistryManager:
    """
    Manages model registration, artifact lineage, and promotion stages for production.
    """

    def __init__(self, config: Optional[AppConfig] = None):
        self.config = config or load_config()
        self.models_dir = self.config.paths.models_dir
        self.manifest_path = self.config.phase2.model_registry.manifest_path
        self.tracking_uri = self.config.mlflow.tracking_uri
        mlflow.set_tracking_uri(self.tracking_uri)
        self.client = MlflowClient(tracking_uri=self.tracking_uri)

    def _compute_file_hash(self, path: Path) -> str:
        """Compute SHA-256 hash of a file for integrity verification."""
        if not path.exists():
            return "NOT_FOUND"
        sha = hashlib.sha256()
        with open(path, "rb") as f:
            for chunk in iter(lambda: f.read(65536), b""):
                sha.update(chunk)
        return sha.hexdigest()

    def get_training_summary(self) -> Dict[str, Any]:
        """Load the training summary generated by src.train."""
        summary_path = self.models_dir / "training_summary.json"
        if not summary_path.exists():
            return {}
        with open(summary_path, "r", encoding="utf-8") as f:
            return json.load(f)

    def get_evaluation_metrics(self) -> Dict[str, Any]:
        """Load binary evaluation metrics from reports/metrics.json."""
        metrics_path = self.config.paths.metrics_path
        if not metrics_path.exists():
            return {}
        with open(metrics_path, "r", encoding="utf-8") as f:
            return json.load(f)

    def get_feature_metadata(self) -> Dict[str, Any]:
        """Load feature schema and scaler parameters."""
        meta_path = self.config.paths.features_meta_path
        if not meta_path.exists():
            return {}
        with open(meta_path, "r", encoding="utf-8") as f:
            return json.load(f)

    def build_registry_manifest(self, champion_name: str = "random_forest") -> Dict[str, Any]:
        """
        Assemble the complete production model registry manifest.
        """
        summary = self.get_training_summary()
        metrics = self.get_evaluation_metrics()
        meta = self.get_feature_metadata()

        champion_file = self.models_dir / f"{champion_name}.joblib"
        champion_hash = self._compute_file_hash(champion_file)

        manifest = {
            "registry_version": "2.1.0",
            "last_updated": datetime.utcnow().isoformat() + "Z",
            "active_champion": {
                "model_name": champion_name,
                "model_class": "RandomForestClassifier",
                "stage": "Production",
                "version": "1.0.0",
                "artifact_path": str(champion_file),
                "sha256": champion_hash,
                "mlflow_experiment": self.config.mlflow.experiment_name,
                "mlflow_run_id": summary.get(champion_name, {}).get("run_id", "N/A"),
                "metrics": metrics.get(champion_name, {}),
                "quality_passed": (
                    metrics.get(champion_name, {}).get("accuracy", 0.0) >= self.config.phase2.quality_gates.min_accuracy
                    and metrics.get(champion_name, {}).get("roc_auc", 0.0) >= self.config.phase2.quality_gates.min_roc_auc
                ),
            },
            "candidate_models": {},
            "feature_contract": {
                "total_features": len(meta.get("feature_columns", [])),
                "century_21_core_skills": CENTURY_21_SKILLS,
                "all_feature_columns": meta.get("feature_columns", []),
                "scaler_fitted_on": meta.get("scaler_train_samples", 0),
            },
            "governance": {
                "framework": "scikit-learn",
                "python_runtime": "3.11.9",
                "license": "MIT",
                "inference_service": "FastAPI (REST / OpenAPI 3.0)",
            },
        }

        # Add candidate models
        for name in ["decision_tree", "logistic_regression"]:
            model_path = self.models_dir / f"{name}.joblib"
            manifest["candidate_models"][name] = {
                "stage": "Staging",
                "artifact_path": str(model_path),
                "sha256": self._compute_file_hash(model_path),
                "mlflow_run_id": summary.get(name, {}).get("run_id", "N/A"),
                "metrics": metrics.get(name, {}),
            }

        return manifest

    def save_manifest(self, champion_name: str = "random_forest") -> Path:
        """Build and write the registry manifest to disk."""
        manifest = self.build_registry_manifest(champion_name=champion_name)
        self.manifest_path.parent.mkdir(parents=True, exist_ok=True)
        with open(self.manifest_path, "w", encoding="utf-8") as f:
            json.dump(manifest, f, indent=2)
        logger.success(f"Model registry manifest written to {self.manifest_path}")
        return self.manifest_path

    def register_in_mlflow(self, champion_name: str = "random_forest") -> Optional[str]:
        """
        Register champion model in MLflow Model Registry and tag it with stage 'Production'.
        """
        summary = self.get_training_summary()
        run_id = summary.get(champion_name, {}).get("run_id")
        if not run_id:
            logger.warning(f"No MLflow run_id found for '{champion_name}'. Skipping MLflow registry call.")
            return None

        reg_name = self.config.phase2.model_registry.registered_model_name
        model_uri = f"runs:/{run_id}/model"

        try:
            reg_model = mlflow.register_model(model_uri=model_uri, name=reg_name)
            logger.info(f"Registered model '{reg_name}' version {reg_model.version} in MLflow.")

            # Transition model to Production
            self.client.transition_model_version_stage(
                name=reg_name,
                version=reg_model.version,
                stage="Production",
                archive_existing_versions=True,
            )
            # Add metadata tags
            self.client.set_model_version_tag(
                name=reg_name,
                version=reg_model.version,
                key="champion_algorithm",
                value="RandomForestClassifier",
            )
            self.client.set_model_version_tag(
                name=reg_name,
                version=reg_model.version,
                key="phase",
                value="Phase 2 Production",
            )
            logger.success(f"Successfully promoted model '{reg_name}' v{reg_model.version} to Production.")
            return reg_model.version
        except Exception as e:
            logger.warning(f"MLflow model registration notice: {e}. Local registry manifest remains fully intact.")
            return None

    def load_champion_model(self) -> Tuple[Any, Dict[str, Any]]:
        """
        Load the champion model estimator and associated feature metadata.
        """
        champion_name = self.config.phase2.api.champion_model_name
        model_path = self.models_dir / f"{champion_name}.joblib"
        if not model_path.exists():
            raise FileNotFoundError(f"Champion model artifact missing at {model_path}. Run training pipeline first.")

        estimator = joblib.load(model_path)
        meta = self.get_feature_metadata()
        return estimator, meta


def run_registry_pipeline() -> Path:
    """Entry point for executing model registration and manifest generation."""
    reg = ModelRegistryManager()
    reg.register_in_mlflow()
    manifest_path = reg.save_manifest()
    return manifest_path


if __name__ == "__main__":
    run_registry_pipeline()
